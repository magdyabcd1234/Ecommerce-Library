export function getCourseQuiz(course, lessons = []) {
  if (!course) return []

  // البحث بالمعرف اللغوي أو الاسم أو العنوان
  const key = course.languageId || course.language || course.title
  if (key && courseQuizzes[key]) {
    return courseQuizzes[key]
  }

  // في حال كان عنوان المسار يحتوي على أحد المفاتيح
  for (const [subj, questions] of Object.entries(courseQuizzes)) {
    if (course.title && course.title.includes(subj)) {
      return questions
    }
  }

  // آلية احتياطية من الدروس في حال وجود مسار مستقبلي غير مسجل
  return Array.from({ length: 10 }, (_, questionIndex) => {
    if (course.courseType === 'world-language' && lessons.length > 0) {
      const lessonIndex = (questionIndex * 47) % lessons.length
      const lesson = lessons[lessonIndex]
      const choices = [lesson.output]
      for (let offset = 29; choices.length < 4 && offset < lessons.length; offset += 1) {
        const answer = lessons[(lessonIndex + offset) % lessons.length].output
        if (!choices.includes(answer)) choices.push(answer)
      }
      return {
        prompt: `ما معنى العبارة «${lesson.code}»؟`,
        choices,
        answer: lesson.output,
      }
    }

    const lesson = lessons[questionIndex % Math.max(1, lessons.length)] || { title: course.language || 'هذا الدرس', code: 'كود تجريبي' }
    return {
      prompt: `ما هو المفهوم الأساسي المرتبط بـ «${lesson.title}» في مسار ${course.language || course.title}؟`,
      choices: [
        `تطبيق المفاهيم الأساسية لـ ${course.language || 'اللغة'} بكفاءة`,
        `إيقاف تشغيل الخادم وتفريغ الذاكرة`,
        `حذف المتغيرات من شجرة المكونات`,
        `تحويل الكود إلى ملف نصي فقط`,
      ],
      answer: `تطبيق المفاهيم الأساسية لـ ${course.language || 'اللغة'} بكفاءة`,
    }
  })
}
